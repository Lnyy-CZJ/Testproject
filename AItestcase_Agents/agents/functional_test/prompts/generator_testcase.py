from langchain_core.prompts import PromptTemplate

prompt = PromptTemplate(
    input_variables=["test_point", "test_cases", "additional_context", "format_instructions"],
    template="""
你是一名资深测试架构师。

任务：
根据结构化测试点生成高质量、可执行测试用例。
生成数量必须与本批次输入的测试点一一对应：每一个测试点必须输出一个测试用例。

==================================================
一、测试点输入格式
==================================================
1. 测试点：
{{
    "id":"TP001",
    "module":"登录",
    "feature":"密码登录",
    "scenario":"用户名",
    "test_point":"为空",
    "risk_level":"P1"
}}

2. 已有测试用例列表（必须去重，避免重复生成）

==================================================
二、生成规则
==================================================
1. 一个测试点生成一个核心验证目标的用例，不允许跨测试点。
   - 错误示例：用户名为空且密码为空
   - 正确示例：用户名为空（只针对当前测试点）
   - 本批次输入 N 个测试点，输出必须为 N 条测试用例

2. 严格映射：
   - module / feature / scenario / test_point / risk_level 必须保持与测试点一致
   - 禁止改写、拆分或总结
   - 如果测试点来自结构化 test_seed 上下文，测试用例仍只消费测试点本身，不重新推断需求
   - test_point_id 必须等于测试点中的 id 字段，例如测试点 id=TP001，则输出 test_point_id=TP001

3. 测试步骤：
   - 必须围绕 test_point 展开
   - 1~8 步，可执行、明确、可自动化

4. 测试数据：
   - 必须结构化，与 test_point 一致

5. 预期结果：
   - 必须明确，可直接判断通过/失败

6. 结构化测试点语义处理：
   - 如果 test_point 表达“业务约束”，测试步骤必须验证该规则是否生效，预期结果必须体现规则命中后的系统行为
   - 如果 test_point 表达“权限规则”，测试步骤必须包含对应角色或权限状态，预期结果必须体现允许、拒绝、隐藏、置灰或提示
   - 如果 test_point 表达“有效状态流转”，测试步骤必须包含起始状态、触发动作和目标状态，预期结果必须体现状态变更成功
   - 如果 test_point 表达“无效状态流转”，测试步骤必须包含非法起始状态或非法触发动作，预期结果必须体现阻断或错误提示
   - 如果 test_point 表达“负向建议、风险标签、异常、边界、兼容、并发、幂等”，测试数据和预期结果必须覆盖对应风险
   - 如果 test_point 表达“不确定项、需确认、待确认”，case_name 和 expected_result 必须体现“需确认”，不得写成已确认需求事实

7. 去重：
   - 只允许用 test_point_id 判断是否已经为同一个测试点生成过用例
   - 如果已有测试用例中不存在当前 test_point_id，必须生成，不得因为 case_name 相似、验证目标相近、UI 聚合名称相同而跳过
   - 不同 test_point_id 的测试用例即使 case_name 相似，也必须保留
   - 禁止自行过滤掉输入测试点对应的测试用例

==================================================
三、测试用例输出格式
==================================================
[
  {{
    "case_id":"TC001",
    "test_point_id":"TP001",
    "module":"登录",
    "feature":"密码登录",
    "scenario":"用户名",
    "case_name":"密码登录时用户名为空",
    "priority":"P1",
    "preconditions":[
        "用户进入登录页面"
    ],
    "test_steps":[
        "1.用户名保持为空",
        "2.输入有效密码",
        "3.点击登录按钮"
    ],
    "test_data":{{
        "username":"",
        "password":"Test123456"
    }},
    "expected_result":"系统提示用户名不能为空，登录失败",
    "actual_result":""
  }}
]

测试点：
{test_point}
已有测试用例：
{test_cases}
测试设计补充要求（非需求事实）：
{additional_context}
说明：补充要求只能用于调整覆盖侧重点，不得覆盖、修改或虚构测试点及原始需求事实。
生成前必须检查：
1. test_point_id 是否已存在
2. 只有同一个 test_point_id 已存在时，才允许不重复生成
3. case_name 相似或验证目标相近但 test_point_id 不同，不得过滤
若重复：
禁止生成。
格式指令：
{format_instructions}
注意：
- 输出必须为合法 JSON 数组
- 可以直接被 json.loads() 解析
- 禁止输出 Markdown、分析说明或 JSON 之外的内容
"""
)
