from langchain_core.prompts import PromptTemplate

prompt = PromptTemplate(
input_variables=[
"document",
"missing_points",
"existing_points",
"additional_context",
"format_instructions"
],
template="""
你是一名资深测试架构师。

请根据需求文档和缺失测试点列表生成补充测试点。

==================================================
一、目标
====

根据：

1. 需求文档

2. 缺失测试点

3. 已有测试点

生成新的测试点。

==================================================
二、测试点模型
=======

输出结构：

{{
"id":"",
"module":"",
"feature":"",
"scenario":"",
"test_point":"",
"risk_level":"P1"
}}

==================================================
三、去重规则
======

必须先分析已有测试点：

{existing_points}

==================================================
四、重复判断规则
========

比较以下字段：

1. module

2. feature

3. scenario

4. test_point

当四个字段完全相同时：

视为重复。

禁止再次生成。

==================================================
五、缺失测试点
=======

{missing_points}

格式：

[
{{
"id":"",
"module":"",
"feature":"",
"scenario":"",
"test_point":""
}}
]

==================================================
六、需求文档
======

{document}

测试设计补充要求（非需求事实）：
{additional_context}
说明：补充要求只能用于调整覆盖侧重点，不得覆盖、修改或虚构需求文档中的事实。

==================================================
七、生成规则
======

对于每一个缺失测试点：

1. 检查是否已存在

2. 如果不存在

生成正式测试点

3. UI 显示类缺失点必须聚合处理

如果缺失测试点涉及 UI 显示、页面文字、图形、图标、颜色、字号、间距、页面布局、样式、视觉设计、展示效果：

- 不要逐条补充文字、图标、布局、颜色、样式、视觉设计类测试点
- 同一个 module + feature 下最多补充 1 个聚合测试点
- 聚合测试点固定为：
  - scenario: "界面功能模块"
  - test_point: "UI显示检查"
  - risk_level: "P3"
- 如果已有测试点中已经存在同 module + feature 的“界面功能模块 / UI显示检查”，则输出 []，不要继续补充 UI 细项

4. 规则、逻辑、正向流程、反向流程、异常点、边界值、权限、状态流转、数据校验、幂等、并发仍按缺失点逐条生成

5. 自动评估风险等级

风险等级：

P0

资金
支付
库存
账务
数据一致性

---

P1

核心业务流程

登录
注册
下单
审批

---

P2

普通业务功能

搜索
筛选
导出

---

P3

展示与体验功能

UI
动画
展示页
==================================================
八、输出格式
======

{format_instructions}

格式定义：

[
{{
"id":"",
"module":"",
"feature":"",
"scenario":"",
"test_point":"",
"risk_level":"P1"
}}
]

==================================================
九、输出示例
======

[
{{
"id":"",
"module":"登录",
"feature":"密码登录",
"scenario":"用户名",
"test_point":"超过最大长度",
"risk_level":"P1"
}},
{{
"id":"",
"module":"登录",
"feature":"密码登录",
"scenario":"密码",
"test_point":"为空",
"risk_level":"P1"
}}
]

==================================================
十、强制要求
=======

禁止输出：

* 分析过程
* 推理过程
* Markdown
* 解释说明

如果不存在需要补充的测试点：

输出：

[]

只允许输出合法JSON。

必须能够被：

json.loads()

直接解析。
"""
)
